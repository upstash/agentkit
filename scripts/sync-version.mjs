#!/usr/bin/env node
// Stamps each package's own version into its `version.ts` constant, so the telemetry header reports
// the real published version.
//
// Python packages under `python/*` are versioned by Changesets through a private `package.json`
// (PyPI has no Changesets support of its own), so their version is copied from there into
// `pyproject.toml` and the package's `_version.py`. `ci:version` re-locks `uv.lock` afterwards.
//
// This runs at **release time only** (`pnpm ci:version`, right after `changeset version` bumps the
// package.json files), so the constant lands in the release PR alongside the version bump. Builds and
// dev never rewrite tracked source.
//
//   node scripts/sync-version.mjs           # write
//   node scripts/sync-version.mjs --check   # verify only, non-zero exit on drift (used by CI)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Package dir → the generated constant's path within it.
const TARGETS = {
  "packages/sdk": "src/version.ts",
  "packages/ai-sdk": "src/version.ts",
  "packages/eve": "src/version.ts",
  "packages/eve-extension": "extension/lib/version.ts",
  "packages/tanstack-ai": "src/version.ts",
  "packages/mcp-toolkit": "src/version.ts",
};

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const stale = [];

const versionOf = (pkgDir) =>
  JSON.parse(readFileSync(join(root, pkgDir, "package.json"), "utf8")).version;

/** Write `contents` to `pkgDir/target`, or record it as stale under `--check`. */
const stamp = (pkgDir, target, version, contents) => {
  const path = join(root, pkgDir, target);
  if (readFileSync(path, "utf8") === contents) return;
  if (check) stale.push(`${pkgDir}/${target} (expected ${version})`);
  else writeFileSync(path, contents);
};

for (const [pkgDir, target] of Object.entries(TARGETS)) {
  const version = versionOf(pkgDir);
  stamp(
    pkgDir,
    target,
    version,
    `// Generated by scripts/sync-version.mjs (run by \`pnpm ci:version\`) — do not edit by hand.
export const VERSION = "${version}";
`,
  );
}

// Python packages are discovered rather than listed: a new one is a new folder under `python/`.
// The module is the distribution name with `-` → `_` (`upstash-hermes-memory` → `upstash_hermes_memory`).
const pythonRoot = join(root, "python");
const pythonDirs = existsSync(pythonRoot)
  ? readdirSync(pythonRoot).filter((d) => existsSync(join(pythonRoot, d, "pyproject.toml")))
  : [];

for (const dir of pythonDirs) {
  const pkgDir = `python/${dir}`;
  const version = versionOf(pkgDir);
  const pyproject = readFileSync(join(root, pkgDir, "pyproject.toml"), "utf8");
  // Only the `version` key of `[project]` — the first `version = ` line at the start of a line.
  stamp(
    pkgDir,
    "pyproject.toml",
    version,
    pyproject.replace(/^version = ".*"$/m, `version = "${version}"`),
  );
  const { name } = JSON.parse(readFileSync(join(root, pkgDir, "package.json"), "utf8"));
  stamp(
    pkgDir,
    `src/${name.replace(/-/g, "_")}/_version.py`,
    version,
    `# Generated by scripts/sync-version.mjs (run by \`pnpm ci:version\`) — do not edit by hand.
VERSION = "${version}"
`,
  );
}

if (check && stale.length > 0) {
  console.error(
    `Stale version constants — run \`node scripts/sync-version.mjs\`:\n  ${stale.join("\n  ")}`,
  );
  process.exit(1);
}
